"""
synthetic_data.py — NEXPIRE Model A
=====================================
Synthetic training data generator.

!! IMPORTANT: ALL DATA GENERATED BY THIS MODULE IS SYNTHETIC !!
   It is generated from hand-crafted statistical distributions and
   does NOT represent real retailer sales, actual demand, or real
   inventory data. This module exists solely to bootstrap the model
   before real feed integration.

   When real retailer data is available, replace the call to
   generate_synthetic_dataset() in train_model.py with your real
   data loader — the interface (column names, types) must remain the same.

Generation philosophy:
  - Per-category shelf-life distributions match category_shelf_life.json.
  - Per-category price-elasticity curves with realistic noise.
  - Simulated weather correlation (hot days → more beverage/fresh produce demand,
    rain → less foot traffic, weekends → higher foot traffic).
  - Time-indexed rows (date column) to enable time-based train/test split.
  - Reproducible via fixed random seed (default: 42).
  - Distribution choices documented in docstrings inline.

Columns produced (16 features + target):
  date, category, sku_id, store_id,
  urgency_score,                        # engineered from days_to_expiry
  days_to_expiry,                       # raw (kept for audit; NOT fed to model)
  current_price, cost_price,
  qty_on_hand,
  avg_daily_velocity_7d, avg_daily_velocity_28d,
  temperature_today, precip_probability,
  is_weekend, is_holiday, hour_of_day,
  store_foot_traffic_index,
  past_discount_depth, past_sellthrough_rate,
  local_demand_score,
  b2b_flag,
  cat_x_temp,                           # interaction: category weather sensitivity × temperature
  cat_x_precip,                         # interaction: category weather sensitivity × precip
  sell_probability                      # TARGET: P(sold within remaining window at current price)
"""

from __future__ import annotations

import json
import math
from datetime import date, timedelta
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np
import pandas as pd

# !! Synthetic data flag — must remain visible !!
